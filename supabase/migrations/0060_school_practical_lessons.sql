## 3つの時間軸を使い分ける

役割の異なる3つの足を見ます。

1. **環境認識足(上位足)**: 日足・4時間足 → 大局のトレンドはどっち向きか
2. **戦略足(中位足)**: 1時間足 → どこで反発しそうか、シナリオを作る
3. **執行足(下位足)**: 5分・15分足 → 具体的なエントリーの引き金を引く

## 「木を見て森も見る」

下位足だけを見ると、大きな流れを見失います。

:::warning
5分足で「上昇トレンドだ!」と買っても、日足では明確な下降トレンドの「戻り」局面だった——これは典型的な負けパターンです。下位足の小さな動きは、上位足の大きな波に簡単に飲み込まれます。
:::

## 上位足に従う、という規律

:::example
日足: 上昇トレンド(森の方向は「上」)。
1時間足: 押し目を作って、サポートに接近(シナリオ「ここで買い」)。
5分足: サポートで反発の確定足が出た(引き金)。
→ 3つの時間軸が「買い」で揃った。これがMTFで根拠が重なった状態=高勝率のエントリーです。
:::

## 時間軸を絞りすぎない・広げすぎない

見る時間軸は **3つ程度** が適切です。

- 1つだけ → 大局を見失う
- 5つも6つも → 情報過多で判断が固まる(分析麻痺)

:::tip
おすすめの組み合わせは「`日足 / 1時間足 / 5分足`」や「`4時間足 / 15分足 / 1分足`」のように、**約4〜6倍ずつ離れた3つ**です。隣り合う時間軸が近すぎると、同じ景色を二度見るだけになります。
:::

MTF分析を身につけると、「なんとなく」のエントリーが消え、すべての売買に「上位足がこうだから」という明確な根拠が伴うようになります。$ja$
