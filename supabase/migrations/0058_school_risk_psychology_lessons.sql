## 人は損失を約2倍重く感じる

:::key
**損失回避(Loss Aversion)**: 1万円を得る喜びより、1万円を失う痛みのほうが、約2倍強い。人間の脳は、利益と損失を対称に評価しないのです。
:::

この非対称性が、トレードのあらゆる失敗の根っこにあります。

## 利益が出ると「臆病」になる

含み益が出ているとき、人はリスクを避けたくなります。

:::example
「+1万円の含み益」と「コインを投げて表なら+2万円、裏なら0円」。期待値は同じなのに、多くの人は確実な+1万円を選びます。だから含み益はすぐ確定したくなる — **チキン利食い**の正体です。
:::

## 損失が出ると「ギャンブラー」になる

逆に含み損を抱えると、人はリスクを取りたくなります。

:::example
「−1万円の確定損」と「コインを投げて表なら0円、裏なら−2万円」。やはり期待値は同じなのに、多くの人は損切りを拒否してギャンブルに賭けます。「戻るまで待つ」「ナンピンする」 — **塩漬けやコツコツドカン**の正体です。
:::

## だから人は、自然にやると必ず負ける

- 利益局面: 早く利確 → 利が**小さく**なる
- 損失局面: 損切り拒否 → 損が**大きく**なる

:::warning
これがプロスペクト理論が示す残酷な真実です。本能のままにトレードすると、リスクリワード比は必ず悪化します。前章で学んだ「RR」を確保できないのは、手法のせいではなく、この心理バイアスのせいなのです。
:::

