## なぜ押し目買いが優位なのか

急騰を見て高値で買うと、損切りが遠くなりリスクが大きくなります。一方、押し目を待つと:

- エントリー価格が**有利**になる
- 損切りまでの距離が**短く**なる(=リスクが小さい)
- 結果として**リスクリワード比が改善**する

## 押し目の探し方

「どこまで押すか」の目安になるのが、次のポイントです。

1. **直近のサポート/レジスタンス**(前の高安)
2. **移動平均線**(20MA・75MAなどへのタッチ)
3. **フィボナッチ・リトレースメント**(38.2%・50%・61.8%)

:::example
上昇トレンド中、価格が直近高値から50%押して、ちょうど75MA付近で下げ止まった。ローソク足が反発を示したらエントリー、直近安値の少し下に損切り。これが教科書的な押し目買いです。
:::

## 「落ちるナイフ」を掴まない

押し目買いの最大の罠は、トレンド転換を「押し目」と勘違いすることです。

:::warning
下落が止まらないのに「そろそろ反発するはず」と買うのは、押し目買いではなく`逆張りのナンピン`です。必ず「反発のサイン(下ヒゲ・反発の確定足)」を待ってから入りましょう。サポートに「タッチした」だけで飛び込まないことが重要です。
:::

