## リスクリワード比(RR)とは

1回のトレードで、`リスク(損切り幅)` に対して `リワード(利確幅)` がどれだけあるか。これがRRです。

:::key
RR = リワード ÷ リスク。損切り20pips・利確60pipsなら **RR = 3.0**。RRが高いほど、低い勝率でも利益が残ります。
:::

## 勝率とRRの損益分岐点

勝ち続けるために必要な最低勝率は、RRから逆算できます。

:::example
- RR = 1.0 → 損益分岐の勝率は **50%**
- RR = 2.0 → 必要勝率は約 **33%**
- RR = 3.0 → 必要勝率は **25%** でよい

つまりRR3.0なら、4回に1回しか勝てなくてもトータルで勝てます。「勝率が低い=ダメ」ではないのです。
:::

## 期待値で考える

トレードの良し悪しは、1回の勝ち負けではなく**期待値**で判断します。

期待値 = (勝率 × 平均利益) −(負け率 × 平均損失)

:::tip
この値がプラスである限り、短期的に連敗しても、試行回数を重ねれば資産は右肩上がりになります。分析タブの`PF(プロフィットファクター)`や`平均RR`は、まさにこの期待値の健全性を映す鏡です。
:::

## ドローダウンは「必ず来る」

どんなに優れた手法でも、連敗の谷(ドローダウン)は必ず訪れます。

:::warning
期待値がプラスの手法でも、確率的に10連敗は普通に起こります。これを「手法が壊れた」と勘違いして手法を捨てると、回復局面を取り逃します。連敗は**バグではなく仕様**です。
:::

## 破産確率を下げる

1回のリスクを下げるほど、長期の破産確率は劇的に下がります。

- 1回2%リスク + プラス期待値 → 破産確率はほぼゼロに近づく
- 1回10%以上のリスク → 期待値がプラスでも、連敗で退場し得る

最終的に市場で生き残るのは、最も賢い人でも最も勝率が高い人でもなく、**最も大きく負けなかった人**です。$ja$
