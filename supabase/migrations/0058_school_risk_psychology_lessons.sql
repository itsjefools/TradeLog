## 攻撃より先に守りを固める

多くの初心者は「どこで買えば儲かるか」ばかりを追いかけます。しかしプロが最初に考えるのは「もし間違っていたら、いくら失うか」です。

- アマチュアの問いは `どれだけ勝てるか`
- プロの問いは `どれだけ負けても生き残れるか`

この視点の違いが、長期的な結果を決定的に変えます。

## 一度の大損が、すべてを奪う

資金は「掛け算」で増減します。だからこそ、一度の大きな損失が致命傷になります。

:::warning
50%の損失を取り戻すには、残った資金を**100%**増やさなければなりません。20万円が10万円に減ったら、元に戻すには倍にする必要があるのです。大きく負けるほど、回復は指数関数的に難しくなります。
:::

## リスク管理とは「確率に賭け続ける権利」を守ること

トレードは1回ごとの勝ち負けではなく、何百回もの試行の積み重ねです。優位性のある手法でも、短期的には連敗します。その連敗を耐え抜き、試行回数を稼ぐための「資金」を守ることこそがリスク管理の本質です。

:::tip
このスクールの続きの章では、`1トレードあたりのリスク`、`ロットサイズの計算`、`損切りの置き方`、`リスクリワード比` を順に学びます。すべては「生き残る」という一つの目的につながっています。
:::

