## 知っていることと、できることは違う

「高値で買うな」「損切りは早く」。誰もが知っています。しかし実際の相場では、知識と正反対の行動を取ってしまう。なぜでしょうか。

- 含み益が出ると、`早く確定したくて` 利を伸ばせない
- 含み損が出ると、`認めたくなくて` 損切りできない
- 急騰を見ると、`乗り遅れたくなくて` 高値で飛び乗る

これらはすべて、知識ではなく**感情**が引き起こす行動です。

## 損失は「痛み」として脳に刻まれる

人間の脳は、利益の喜びよりも損失の痛みを**約2倍**強く感じるようにできています(この性質は次章で詳しく学びます)。

:::warning
この「痛みを避けたい」本能が、損切りを遅らせ、利確を早めます。つまり私たちの脳は、生まれつき「損は大きく、利は小さく」する方向に設計されているのです。トレードで勝つには、この本能に逆らう訓練が必要です。
:::

## 規律とは「ルールに従う筋肉」

感情をゼロにすることはできません。プロも恐怖や欲望を感じます。違いは、感情に**従わない**訓練ができているかどうかです。

:::tip
感情をコントロールしようとするのではなく、`事前に決めたルール`に従うことに集中しましょう。エントリー、損切り、利確、ロット — すべてを冷静なときに決め、相場が動いている最中は「ルールを実行するだけ」にするのです。
:::

