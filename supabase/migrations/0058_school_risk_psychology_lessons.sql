## ロット計算の公式

ロットサイズは、たった一つの式から逆算できます。

:::key
**ロット = 許容損失額 ÷ (損切り幅[pips] × 1pipの価値)**

「いくらまで失えるか」と「損切りまで何pipsか」が決まれば、ロットは自動的に決まります。
:::

:::diagram:lot_size:::

## 具体例で計算する

:::example
資金100万円、2%ルール(許容損失 `2万円`)、USD/JPY で損切り幅 `20pips` の場合:

1ロット(10万通貨)あたり1pip ≈ 1,000円。
20pips × 1,000円 = 1ロットあたり2万円の損失。
→ 許容損失2万円 ÷ 2万円 = **1.0ロット** が答えです。

もし損切り幅が40pipsに広がるなら、ロットは半分の0.5ロットに減らします。
:::

## 損切りが広いほど、ロットは小さく

ここが最も重要なポイントです。多くの初心者は逆をやってしまいます。

- 損切りが**広い**(値幅が大きい) → ロットを**小さく**する
- 損切りが**狭い**(値幅が小さい) → ロットを大きくできる

こうすることで、損切り幅が変わっても1回の損失額は常に一定(資金の2%)に保たれます。

:::warning
「ロットを固定する」のは危険です。同じ1ロットでも、損切り20pipsと100pipsではリスクが5倍違います。固定すべきは**ロットではなく損失額**です。
:::

