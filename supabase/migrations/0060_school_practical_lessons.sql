## デイトレに向いた時間帯

通貨ペアごとに「動く時間」があります。

- **東京時間(9:00〜15:00)**: 値動きは穏やか。レンジになりやすい
- **ロンドン時間(16:00〜)**: 流動性が増え、トレンドが出やすい
- **NY時間(21:00〜)**: 経済指標が多く、最も活発

:::tip
兼業トレーダーは、無理に一日中見るのではなく`ロンドン〜NYの重なる時間(21:00〜翌1:00頃)`だけに集中するのも有効です。動く時間だけを狙えば、効率よくチャンスを取れます。
:::

## 1日の流れを組み立てる

デイトレは「思いつき」ではなく「計画」で行います。

1. **環境認識**: 上位足(4時間・日足)で今日の方向感を確認する
2. **シナリオ**: 「この水準で反発したら買い」など、複数の筋書きを用意する
3. **執行**: 条件が来たらルール通りエントリー、損切り・利確を必ずセット
4. **手仕舞い**: その日の取引終了時刻に、ポジションを残さず決済する

:::warning
「もう少しで利益が伸びそう」という理由で日をまたぐのは、デイトレードではありません。それはルール違反であり、最も危険な`含み損の持ち越し`につながります。
:::

