## なぜ2%なのか

口座資金100万円なら、1トレードの最大損失は2万円。この基準を守ると、たとえ連敗してもダメージは限定的です。

- 1回の損失 = `資金 × 2%`
- 連敗してもゆっくりとしか資金は減らない
- 立て直す時間と精神的余裕が残る

## 連敗への耐性を計算してみる

2%ルールを守ると、理論上どれだけの連敗に耐えられるでしょうか。

:::example
資金100万円・1回2%リスクの場合、10連敗しても資金は約82万円残ります(複利で計算)。一方、1回20%もリスクを取ると、わずか**3連敗**で資金は半分近くまで溶けます。同じ連敗でも、結果はまるで違います。
:::

## 初心者はもっと小さく

メンタルがまだ鍛えられていない初心者は、`1%` あるいは `0.5%` から始めるのが賢明です。リスクを小さくするほど、1回の負けに動揺しなくなり、冷静な判断を保てます。

:::warning
「早く増やしたい」という焦りから、1回のトレードに大きく賭けるのは破滅への近道です。リスクを2倍にしても、増えるスピードが2倍になるだけでなく、退場確率はそれ以上に跳ね上がります。
:::

