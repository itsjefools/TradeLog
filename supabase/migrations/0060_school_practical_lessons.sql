## 狙うべきブレイクのポイント

- **レンジの上限/下限**(明確な水平線)
- **トレンドライン**の突破
- **三角保ち合い(ペナント)**からの放れ
- **前日高値・安値**、キリの良い節目

## だましを避ける2つの工夫

ブレイクアウトの最大の敵は「**だまし(フェイクブレイク)**」です。抜けたと思ったら、すぐに戻されて損切りになるパターンです。

:::warning
ヒゲで一瞬抜けただけで飛び乗ると、だましに引っかかります。`ローソク足の実体で明確に抜けて確定する`のを待つことで、多くのだましを回避できます。
:::

:::tip
さらに堅実なのが**リテスト**を待つ方法です。一度ブレイクした後、抜けたライン(旧レジスタンスが新サポートに変わる)まで戻ってきて、反発を確認してからエントリーする。だましを大きく減らせます。
:::

## 出来高・勢いを確認する

本物のブレイクアウトには「勢い」が伴います。

1. 抜ける瞬間のローソク足が**大きい(勢いがある)**
2. 抜けた後、力強く伸びていく
3. 重要な経済指標や、市場が活発な時間帯と重なっている

:::example
