## 欲望が引き起こす失敗

欲望は「もっと欲しい」という感情です。

- **高値掴み**: 急騰を見て「乗り遅れたくない」と飛び乗る(FOMO)
- **利確できない**: 含み益が出ても「まだ伸びる」と欲張り、結局含み損に
- **過剰ロット**: 「一気に増やしたい」と無謀なロットを張る

:::example
価格が急騰し、SNSが盛り上がっている。「今乗らないと損だ」と感じて高値で買う。その瞬間が、しばしば天井です。あなたが感じた`欲望`は、すでに買い終えた人たちが利確をぶつける相手を探しているサインかもしれません。
:::

## 恐怖が引き起こす失敗

恐怖は「失いたくない」という感情です。

- **狼狽売り**: 少し逆行しただけで怖くなり、損切りラインの手前で投げる
- **チキン利食い**: 含み益が減るのが怖くて、すぐに小さく利確する
- **入れない**: 連敗後、優位性のある場面でも怖くてエントリーできない

:::warning
恐怖は「損切り」という正しい行動と、「狼狽売り」という誤った行動の両方を引き起こします。違いは、**事前に決めた損切りか**、**その場の感情で投げたか**です。
:::

## 感情は「逆張りのサイン」になる

ベテランは、自分の強い感情を「警告灯」として使います。

:::tip
「今すぐ買わないと!」と強烈に感じたら、それは高値圏のサインかもしれません。「もう怖くて見ていられない」と感じたら、それは底値圏のサインかもしれません。**大衆が極端な恐怖や欲望に支配されたとき**こそ、相場は反転します。
:::

## 対策:感情を「観察」する

感情を消すのではなく、第三者のように観察します。

1. 「今、自分は欲張っている」と気づく
2. 「これはFOMOだ」とラベルを貼る
3. ラベルを貼った瞬間、感情との間に距離が生まれる
4. その距離があれば、ルール通りに動ける

