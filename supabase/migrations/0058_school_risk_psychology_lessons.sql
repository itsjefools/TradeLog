## トレードルールに必要な5要素

自分のルールを、紙に書けるレベルまで具体化しましょう。

1. **環境認識**: どの相場状況でのみトレードするか
2. **エントリー条件**: 何が起きたら入るか(具体的なサイン)
3. **損切り**: どこに置くか(チャート構造で)
4. **利確**: RRいくつを狙うか、どう決済するか
5. **ロット**: 2%ルールでどう計算するか

:::tip
「裁量トレード」であっても、ルールは必要です。裁量とは「ルールがない」ことではなく、`ルールの範囲内で状況に応じて判断する`ことです。境界線のない自由は、ただの衝動です。
:::

