## 損切りは「チャートの構造」で置く

良い損切りは、「ここまで来たら、自分のシナリオは崩壊する」という価格に置きます。

- 直近の**安値/高値**の少し外側
- **サポート/レジスタンス**を明確に抜けた場所
- 「ここを抜けたら上昇シナリオは無効」という節目

逆に、悪い損切りは「これ以上は損したくない」という金額の都合で置いたものです。

## 「損失額からpips」ではなく「pipsからロット」

順番を間違えないでください。

1. ❌ 「2万円までしか損したくないから、20pipsに損切りを置く」
2. ✅ 「チャートの構造的に30pipsが妥当 → ならロットを調整して損失を2万円に収める」

前のレッスンの公式は、まさにこのためにあります。損切り位置はチャートが決め、ロットで損失額を調整するのです。

:::warning
**損切りを置かない**、あるいは含み損が膨らんでから**損切りをずらす**のは、最も多い破滅パターンです。「もう少し待てば戻る」という期待が、小さな損失を致命傷に変えます。
:::

## 損切り狩りを避ける

ちょうど直近安値の1pip下など、誰もが置く場所は「狩られ」やすいポイントです。

:::tip
キリの良い価格(150.00など)や、直近高安の**すぐ内側**は避け、少し余裕を持たせた位置に置くと、ノイズによる不要な損切りを減らせます。ただし、余裕を持たせた分だけ損切り幅は広がるので、ロットは小さくなります。
:::

